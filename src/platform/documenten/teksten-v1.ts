export function interneLijsten(soort: string, titel: string, toelichting: string): InterneLijst[] {
  const tekst = `${soort} ${titel} ${toelichting}`.toLowerCase();
  const lijsten: InterneLijst[] = [];
  if (soort.trim().toLowerCase() === 'expositie') lijsten.push(CHECKLIST_EXPOSITIE);
  if (soort.trim().toLowerCase() === 'bruiloft' || /huwelijk|bruiloft/.test(tekst)) lijsten.push(DRAAIBOEK_HUWELIJK);
  if (/uitvaart/.test(tekst)) lijsten.push(DRAAIBOEK_UITVAART);
  return lijsten;
}
